"""Tooling for the Harbor dataset in harbor/: generate task files, self-check rubrics, summarize runs.

    uv run python scripts/harbor_tasks.py sync            # RUN AFTER CLONING and after editing _shared/ or a task.toml
    uv run python scripts/harbor_tasks.py sync --check    # exit 1 if any generated file is missing or stale
    uv run python scripts/harbor_tasks.py rubric-checks   # sabotaged solutions vs expected outcomes (harbor/rubric_checks.toml)
    uv run python scripts/harbor_tasks.py summary harbor/results.jsonl [--job kelp-sweep] [--task stealth-send] [--trials]
    uv run python scripts/harbor_tasks.py summary harbor/jobs/<job> --append-results   # after a run: record it

sync — a Harbor task must carry its whole environment, so each task gets generated copies of
harbor/_shared (chain sidecar, agent image, compose overlay, verifier helpers) and its
environment/chain/setup.json, rendered from the [metadata.chain] table of its task.toml. These are
gitignored; a fresh clone has none until sync runs. Edit _shared/ or task.toml, never the copies.
After a sync that changed anything, run `harbor sync` in harbor/ so dataset.toml's digests follow.

rubric-checks — each [[check]] in harbor/rubric_checks.toml is a deliberately wrong solution for
one task (a full `script`, or a `patch` [old, new] applied to the task's gold solve.sh) and the
verifier outcome it must get. Each is copied into a temporary dataset and run with Harbor's oracle
agent (which just runs solve.sh). Exit 1 on any mismatch. Gold / no-op checks are plain
`harbor run -p harbor -a oracle` / `-a nop`.

summary — per-task tables and a model x task grid. Inputs are Harbor job folders (harbor/jobs/,
gitignored: large, regenerated by running) or harbor/results.jsonl (committed: one row per trial
with task, model, outcome, reward, cost, steps and the transactions it sent — from the chain
proxy's log, verifier/interactions.txt, or the typed `cast send` lines for older trials).
--append-results replaces that job's rows in harbor/results.jsonl.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HARBOR = ROOT / "harbor"
RESULTS = HARBOR / "results.jsonl"
COPIES = {  # harbor/_shared source -> path inside each task
    "chain/node.py": "environment/chain/node.py",
    "chain/Dockerfile": "environment/chain/Dockerfile",
    "main/Dockerfile": "environment/Dockerfile",
    "compose.base.yaml": "environment/docker-compose.yaml",
    "tests/chainlib.py": "tests/chainlib.py",
    "tests/test.sh": "tests/test.sh",
}
SETUP = "environment/chain/setup.json"


# --- sync ---------------------------------------------------------------------------------------
def tasks(root: Path = HARBOR) -> list[Path]:
    return sorted(p.parent for p in root.glob("*/task.toml"))


def setup_json(task: Path) -> bytes:
    """The sidecar's setup.json, rendered from task.toml [metadata.chain]."""
    c = tomllib.loads((task / "task.toml").read_text())["metadata"]["chain"]
    setup = {"_case": c.get("case", ""), "fork_block": c["fork_block"], "senders": c["senders"],
             "eth": c.get("eth", {}), "erc20": c.get("erc20", []), "calls": c.get("calls", [])}
    return (json.dumps(setup, indent=2) + "\n").encode()


def generated(task: Path, root: Path = HARBOR) -> dict[Path, bytes]:
    out = {task / dst: (root / "_shared" / src).read_bytes() for src, dst in COPIES.items()}
    out[task / SETUP] = setup_json(task)
    return out


def drift(root: Path = HARBOR) -> list[str]:
    return [f"{p.relative_to(root)}" for t in tasks(root) for p, want in generated(t, root).items()
            if not p.exists() or p.read_bytes() != want]


def sync(root: Path = HARBOR, quiet: bool = False) -> None:
    for t in tasks(root):
        for p, data in generated(t, root).items():
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_bytes() != data:
                p.write_bytes(data)
            if p.suffix == ".sh":
                p.chmod(0o755)
        if not quiet:
            print("synced", t.name)


# --- summary ------------------------------------------------------------------------------------
def trial_rows(job: Path):
    for res in sorted(job.glob("*/result.json")):
        r = json.loads(res.read_text())
        if not r.get("config"):
            continue
        model = r["config"].get("agent", {}).get("model_name") or r["config"].get("agent", {}).get("name", "?")
        model = model.removeprefix("openrouter/")
        task = (r.get("task_name") or "?").split("/")[-1]
        rew = (r.get("verifier_result") or {}).get("rewards") or {}
        vdir = res.parent / "verifier"
        # A verifier that crashed falls back to {"reward": 0} without writing detail.json: that is
        # an unscored trial, not a model failure.
        detail = json.loads((vdir / "detail.json").read_text()) if (vdir / "detail.json").exists() else None
        if rew and detail is None:
            rew = {}
        ag = r.get("agent_result") or {}
        exc = (r.get("exception_info") or {}).get("exception_type", "")
        keys = []
        traj = res.parent / "agent" / "trajectory.json"
        if traj.exists():
            for s in json.loads(traj.read_text()).get("steps", []):
                for tc in s.get("tool_calls") or []:
                    k = (tc.get("arguments") or {}).get("keystrokes")
                    if k:
                        keys.append(k)
        typed = "\n".join(keys)
        if (vdir / "interactions.txt").exists():
            sends = [l for l in (vdir / "interactions.txt").read_text().splitlines()
                     if l.startswith(("eth_sendTransaction", "anvil_", "evm_", "eth_sendRaw"))]
        else:
            sends = [re.sub(r"\s+", " ", m).strip()[:160] for m in re.findall(r"cast send[^\n;&|]*", typed)]
        yield {"trial": res.parent.name, "job": job.name, "task": task, "model": model,
               "reward": rew.get("reward"), "correct": rew.get("correct"),
               "outcome": (detail or {}).get("outcome", "unscored" if not rew else "?"),
               "cost": ag.get("cost_usd") or 0.0, "steps": (ag.get("metadata") or {}).get("n_episodes"),
               "exception": exc, "checked_allowance": "allowance(" in typed, "sends": sends}


def load_rows(paths: list[Path]) -> list[dict]:
    rows = []
    for p in paths:
        if p.suffix == ".jsonl":
            rows += [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
        else:
            rows += list(trial_rows(p))
    return rows


def table(rows: list[dict]) -> None:
    by = defaultdict(list)
    for t in rows:
        by[t["model"]].append(t)
    # A trial with no verifier reward never reached the chain check (provider/infra failure): it is
    # reported in `unscored`, not counted as a model failure.
    print("| model | pass | mean reward | outcomes | $/trial | steps | unscored | exceptions |")
    print("|---|---:|---:|---|---:|---:|---:|---|")

    def key(kv):
        sc = [t for t in kv[1] if t["reward"] is not None]
        return (-sum(t["correct"] or 0 for t in sc) / max(1, len(sc)), sum(t["cost"] for t in kv[1]))
    for m, ts in sorted(by.items(), key=key):
        sc = [t for t in ts if t["reward"] is not None]
        n = len(sc)
        ok = sum(1 for t in sc if t["correct"])
        mr = sum(t["reward"] for t in sc) / n if n else float("nan")
        steps = [t["steps"] for t in ts if t["steps"] is not None]
        outs = ", ".join(f"{k} {v}" for k, v in Counter(t["outcome"] for t in sc).most_common())
        errs = ",".join(sorted({t["exception"] for t in ts if t["exception"]}))
        print(f"| `{m}` | {ok}/{n} | {mr:.2f} | {outs} | {sum(t['cost'] for t in ts)/len(ts):.3f} | "
              f"{sum(steps)/len(steps) if steps else 0:.1f} | {len(ts) - n} | {errs} |")


def grid(rows: list[dict]) -> None:
    task_names = sorted({t["task"] for t in rows})
    print("| model | " + " | ".join(task_names) + " | total |")
    print("|---|" + "---:|" * (len(task_names) + 1))
    for m in sorted({t["model"] for t in rows}):
        cells, ok_all, n_all = [], 0, 0
        for task in task_names:
            sc = [t for t in rows if t["model"] == m and t["task"] == task and t["reward"] is not None]
            ok = sum(1 for t in sc if t["correct"])
            ok_all, n_all = ok_all + ok, n_all + len(sc)
            cells.append(f"{ok}/{len(sc)}" if sc else "–")
        print(f"| `{m}` | " + " | ".join(cells) + f" | {ok_all}/{n_all} |")


def summary(a) -> None:
    rows = load_rows(a.paths)
    if a.append_results:
        jobs = {r["job"] for r in rows}
        keep = [r for r in load_rows([RESULTS]) if r["job"] not in jobs] if RESULTS.exists() else []
        allrows = sorted(keep + rows, key=lambda r: (r["job"], r["task"], r["model"], r["trial"]))
        RESULTS.write_text("".join(json.dumps(r) + "\n" for r in allrows))
        print(f"wrote {len(rows)} rows for {sorted(jobs)} to {RESULTS.relative_to(ROOT)}")
    if a.job:
        rows = [t for t in rows if t["job"] in a.job]
    if a.task:
        rows = [t for t in rows if t["task"] == a.task]
    for task in sorted({t["task"] for t in rows}):
        print(f"\n### {task}\n")
        table([t for t in rows if t["task"] == task])
    if len({t["task"] for t in rows}) > 1:
        print("\n### pass rate by model and task\n")
        grid(rows)
    if a.trials:
        for t in sorted(rows, key=lambda t: (t["task"], t["model"])):
            print(f"\n{t['task']}  {t['model']}  {t['trial']}  outcome={t['outcome']} reward={t['reward']} "
                  f"steps={t['steps']} ${t['cost']:.3f} {t['exception']}")
            for s in t["sends"]:
                print("   ", s[:220])


# --- rubric checks ------------------------------------------------------------------------------
def rubric_checks(a) -> None:
    checks = [c for c in tomllib.loads((HARBOR / "rubric_checks.toml").read_text())["check"] if a.k in c["name"]]
    sync(HARBOR, quiet=True)   # the tasks' generated files must be current
    jobs = HARBOR / "jobs"
    if (jobs / a.job_name).exists():
        shutil.rmtree(jobs / a.job_name)
    with tempfile.TemporaryDirectory() as tmp:
        for c in checks:
            dst = Path(tmp) / c["name"]
            shutil.copytree(HARBOR / c["task"], dst)
            toml = dst / "task.toml"
            toml.write_text(toml.read_text().replace(f'name = "ethereum-dai/{c["task"]}"',
                                                     f'name = "rubric-check/{c["name"]}"', 1))
            solve = dst / "solution" / "solve.sh"
            if "patch" in c:
                old, new = c["patch"]
                gold = solve.read_text()
                assert gold.count(old) == 1, f"{c['name']}: patch target must occur exactly once"
                solve.write_text(gold.replace(old, new))
            else:
                solve.write_text("#!/bin/bash\n" + c["script"])
            solve.chmod(0o755)
        subprocess.run(["harbor", "run", "-p", tmp, "-a", "oracle", "-n", str(a.n), "-o", str(jobs),
                        "--job-name", a.job_name, "-y", "-q"], check=False, cwd=ROOT)
    got = {}
    for res in (jobs / a.job_name).glob("*/result.json"):
        name = json.loads(res.read_text()).get("task_name", "").split("/")[-1]
        detail = res.parent / "verifier" / "detail.json"
        got[name] = json.loads(detail.read_text())["outcome"] if detail.exists() else "unscored"
    bad = 0
    print("\n| check | task | expected | got |\n|---|---|---|---|")
    for c in checks:
        ok = got.get(c["name"]) == c["expected"]
        bad += not ok
        print(f"| {c['name']} | {c['task']} | {c['expected']} | {got.get(c['name'], 'missing')}"
              f"{'' if ok else '  **MISMATCH**'} |")
    print(f"\n{len(checks) - bad}/{len(checks)} as expected")
    sys.exit(1 if bad else 0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sync", help="generate each task's copies of _shared and its setup.json")
    s.add_argument("--check", action="store_true")
    s.add_argument("--root", type=Path, default=HARBOR, help="a harbor/ dataset folder")
    r = sub.add_parser("rubric-checks", help="run harbor/rubric_checks.toml")
    r.add_argument("-k", default="", help="only checks whose name contains this")
    r.add_argument("-n", type=int, default=11, help="concurrent trials")
    r.add_argument("--job-name", default="rubric-checks")
    m = sub.add_parser("summary", help="tables from job folders or harbor/results.jsonl")
    m.add_argument("paths", nargs="+", type=Path)
    m.add_argument("--job", action="append", help="only these jobs (repeatable)")
    m.add_argument("--task", help="only this task (short name, e.g. aave-rescue)")
    m.add_argument("--trials", action="store_true", help="list every trial's transactions")
    m.add_argument("--append-results", action="store_true", help="record these jobs in harbor/results.jsonl")
    a = ap.parse_args()
    if a.cmd == "sync":
        if a.check:
            bad = drift(a.root)
            print("\n".join(bad) or "all tasks in sync")
            sys.exit(1 if bad else 0)
        sync(a.root)
    elif a.cmd == "rubric-checks":
        rubric_checks(a)
    else:
        summary(a)


if __name__ == "__main__":
    main()
